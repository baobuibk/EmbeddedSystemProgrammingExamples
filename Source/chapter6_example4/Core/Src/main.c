void EXTI_PI11_Init_CMSIS(void)
{
    /* 1) Enable clock GPIOI + SYSCFG */
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOIEN;
    RCC->APB2ENR |= RCC_APB2ENR_SYSCFGEN;

    (void)RCC->AHB1ENR;
    (void)RCC->APB2ENR;

    /* 2) GPIOI Pin 11: Input + Pull-up */
    /* MODER11 = 00 (input) */
    GPIOI->MODER &= ~(0x3U << (11U * 2U));

    /* PUPDR11 = 01 (pull-up) */
    GPIOI->PUPDR &= ~(0x3U << (11U * 2U));
    GPIOI->PUPDR |=  (0x1U << (11U * 2U));

    /* 3) Map EXTI11 -> Port I trong SYSCFG_EXTICR3 (EXTI8..11) */
    /* EXTI11 nằm ở EXTICR3, field [15:12] */
    SYSCFG->EXTICR[2] &= ~(0xFU << 12U);
    SYSCFG->EXTICR[2] |=  (0x8U << 12U);  // Port I = 0b1000

    /* 4) Cấu hình EXTI line 11: unmask + falling edge */
    EXTI->IMR  |=  (1U << 11U);   // interrupt request from line 11 not masked
    EXTI->EMR  &= ~(1U << 11U);   // event mask off (không bắt buộc)

    EXTI->RTSR &= ~(1U << 11U);   // tắt rising
    EXTI->FTSR |=  (1U << 11U);   // bật falling

    /* 5) Clear pending (nếu có) */
    EXTI->PR = (1U << 11U);       // write 1 để clear

    /* 6) NVIC: EXTI15_10_IRQn dùng chung cho line 10..15 */
    NVIC_SetPriority(EXTI15_10_IRQn, 5U);
    NVIC_EnableIRQ(EXTI15_10_IRQn);
}


